export type KioskMessageKey = keyof typeof kioskMessages;
export function kioskText(language: string, key: KioskMessageKey, params: Record<string, string | number> = {}): string {
  const locale = ['cn', 'tw', 'en', 'jp', 'ko'].includes(language) ? language as 'cn' | 'tw' | 'en' | 'jp' | 'ko' : 'en';
  return kioskMessages[key][locale].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
