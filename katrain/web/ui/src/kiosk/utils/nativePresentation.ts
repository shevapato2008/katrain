/** Known platform enums are localized only for display; IDs and unknown values pass through. */
const PLATFORM_LABELS: ReadonlySet<string> = new Set([
  '自由战', '升降战', '进行中', '已结束', '拒绝', '创建', '登录', '空闲', '忙碌', '对弈', '离线', '退出',
  '观战', 'AI解题中', '研究中', '允许邀请', '拒绝邀请', '状态未返回',
]);
export function platformLabel(value: string | null | undefined, t: RankTranslation): string {
  if (!value) return '';
  if (PLATFORM_LABELS.has(value)) return t(value, value);
  const moves = value.match(/^(\d+)手$/);
  return moves ? interpolate(t('{n} 手', '{n} 手'), { n: moves[1] }) : value;
}

